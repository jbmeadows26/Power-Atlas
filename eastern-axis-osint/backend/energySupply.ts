function* csvRows(text: string): Generator<string[]> {
  let field = '', fields:string[] = [], quote = false;
  for (let index=0; index<text.length; index++) {
    const c=text[index];
    if(c === '"') {
      if(quote && text[index+1] === '"'){field+='"';index++;}
      else quote=!quote;
    } else if(c === ',' && !quote) {fields.push(field);field='';}
    else if((c === '\n'||c === '\r') && !quote){
      if(c==='\r'&&text[index+1]==='\n')index++;
      fields.push(field);field='';
      if(fields.length>1) yield fields;
      fields=[];
    } else field+=c;
  }
  if(field.length || fields.length){fields.push(field); yield fields;}
}
const tidy=(name:string)=>name.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g,'').replace(/[^a-z0-9]/g,'');
const aliases: Record<string,string> = {
  RU:'russia', CN:'china', KP:'northkorea', KR:'southkorea', IR:'iran',
  TW:'taiwan', GB:'unitedkingdom', TR:'turkey', US:'unitedstates',
  CD:'democraticrepublicofcongo', CZ:'czechia', VA:'vatican',
  PS:'palestine', MM:'myanmar'
};
export async function syncEnergy() {
  const started = new Date().toISOString();
  try {
    const response=await fetch(SOURCE,{
      headers:{Accept:'text/csv, */*'},signal:AbortSignal.timeout(28_000)
    });
    if(!response.ok)throw new Error('OWID CSV HTTP '+response.status);
    const length=Number(response.headers.get('content-length')||0);
    if(length>16_000_000)throw new Error('Unexpected OWID data size');
    const raw=await response.text();
    if(raw.length>16_000_000)throw new Error('OWID payload exceeds configured limit');
    const reader=csvRows(raw);
    const header=reader.next().value;
    if(!header || !header.includes('country') || !header.includes('year') || !header.includes('iso_code') ||
      !header.includes('oil_production_twh') || !header.includes('electricity_generation_twh'))
      throw new Error('OWID energy schema mismatch');
    const indexes=Object.fromEntries(['country','year','iso_code',...cols.map(c=>c.key)].map(c=>[c,header.indexOf(c)]));
    const byCountry:Record<string,EnergyCountry> = {};
    let parsedRows=0;
    for(const row of reader) {
      parsedRows++;
      const name = (row[indexes.country]||'').trim();
      const iso3 = (row[indexes.iso_code]||'').trim();
      const year = Number(row[indexes.year]);
      if(!name || !Number.isInteger(year) || year<1800 || year>2035)continue;
      if(!/^[A-Z]{3}$/.test(iso3) && name !== 'World')continue;
      const key=tidy(name);
      const country = byCountry[key] || {name,iso3,fields:{}};
      for(const col of cols) {
        const str=row[indexes[col.key]];
        if(str===undefined || str==='') continue;
        const value=Number(str);
        if(!Number.isFinite(value))continue;
        if(!country.fields[col.key]||country.fields[col.key].year<year){
          country.fields[col.key]={value,year};
        }
      }
      byCountry[key]=country;
    }
    const countryCount=Object.keys(byCountry).filter(k=>k!=='world').length;
    if(parsedRows<10000 || countryCount<160)throw new Error('OWID energy source completeness guard failed');
    const snap:EnergySnapshot={
      id:'latest',checkedAt:started,fileSha256:createHash('sha256').update(raw,'utf8').digest('hex'),
      sourceUrl:SOURCE,countryCount,parsedRows,byCountry
    };
    if(Buffer.byteLength(JSON.stringify(snap),'utf8')>240_000)throw new Error('OWID summary too large for single snapshot');
    const [ok]=await db.tx.update('global_energy_snapshots',[{id:'latest',record:snap}]);
    if(!ok)throw new Error('OWID snapshot write unconfirmed');
    await db.tx.update('global_energy_health',[{id:'latest',record:{status:'ok',checkedAt:started}}]);
    return {source:'energy',status:'ok',countryCount,parsedRows};
  }catch(e){
    const message=e instanceof Error?e.message:'Energy dataset error';
    await db.tx.update('global_energy_health',[{id:'latest',record:{status:'failed',checkedAt:started,lastError:message.slice(0,200)}}]);
    return {source:'energy',status:'failed',error:message};
  }
}
export async function readEnergy(code:string,countryName?:string) {
  if(code!=='all'&&!/^[A-Z]{2}$/.test(code))return null;
  let [saved]=await db.get<EnergySnapshot>('global_energy_snapshots',['latest'],{consistent:true});
  let warmup:'not-needed'|'attempted'='not-needed';
  if(!saved) {
    warmup='attempted';
    await syncEnergy();
    [saved]=await db.get<EnergySnapshot>('global_energy_snapshots',['latest'],{consistent:true});
  }
  const name=code==='all'?'World':(aliases[code]||tidy(countryName||new Intl.DisplayNames(['en'],{type:'region'}).of(code)||code));
  const country=saved?.byCountry[name]||null;
  return {
    code, checkedAt:saved?.checkedAt||null,
    status:!saved?'unavailable':country?'reported':code==='all'?'global-coverage':'no-country-match',
    sourceName:'Our World in Data / Energy Institute / Ember / EIA',
    sourceUrl:CATALOG,downloadUrl:SOURCE,
    sourceHash:saved?.fileSha256||null,
    countryCount:saved?.countryCount||null,parsedRows:saved?.parsedRows||null,warmup,
    location:country?.name||(code==='all'?'Worldwide coverage':countryName||code),
    indicators:cols.map(c=>({
      ...c,value:country?.fields[c.key]?.value??null,
      year:country?.fields[c.key]?.year??null
    })),
    warning:!saved?'Energy data is not available; the upstream download or validation failed.'
      :code==='all'&&!country?'This international data snapshot covers individual countries. No publisher-verified World aggregate was available; country totals must not be summed into an invented world measurement. Select a country to view annual observations. The revised OWID energy methodology differs from its discontinued legacy dataset.'
      :'Annual energy observations may be published in different years by source and country. The new OWID total-energy-supply methodology is NOT directly comparable to its discontinued legacy dataset.',
    interpretation:'Physical production figures are not verified ownership, exports by destination, supply-chain control or proof of political influence.'
  };
}
