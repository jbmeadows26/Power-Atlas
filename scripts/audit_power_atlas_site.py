#!/usr/bin/env python3
"""Read-only site-wide static data, link and evidence audit for Power Atlas.

Does not contact external sites or claim live-source/API coverage.
Generates a transparent audit that identifies broken static references,
JSON validation, partial original-source coverage and all known source gaps.
"""
from __future__ import annotations

import argparse
from collections import Counter
from datetime import datetime, timezone
from html.parser import HTMLParser
import json
from pathlib import Path, PurePosixPath
import re
from urllib.parse import unquote, urlsplit

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "data/health/sitewide-audit-v1.json"
CATALOG = ROOT / "data/health/sitewide-missing-sources-v1.json"
ISSUES = {"housing", "groceries", "energy", "health", "work", "schools",
          "transport", "public-services", "representation"}
IMPORTANT_ROUTES = (
    "platform/unified/index.html", "platform/unified/my-life.html",
    "platform/unified/corporate-ownership.html",
    "platform/unified/business-influence.html",
    "platform/unified/business-candidates.html",
    "platform/unified/dark-money.html",
    "platform/unified/reform-lab.html",
    "site/index.html", "site/election-2026.html",
    "research/voting-access/index.html",
)

class PageParser(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.links: list[tuple[str, str, str]] = []
        self.ids: set[str] = set()
        self.title = False
        self.scripts: list[str] = []

    def handle_starttag(self, tag: str, attrs):
        attributes = dict(attrs)
        if attributes.get("id"):
            self.ids.add(attributes["id"])
        if tag == "a" and attributes.get("href"):
            self.links.append(("link", attributes["href"], tag))
        if tag in ("script", "img", "source", "iframe", "link"):
            attr = "href" if tag == "link" else "src"
            if attributes.get(attr):
                self.links.append(("asset", attributes[attr], tag))
                if tag == "script":
                    self.scripts.append(attributes[attr])

def read_json(path: Path):
    return json.loads(path.read_text(encoding="utf-8-sig"))

def rel(path: Path) -> str:
    return str(path.relative_to(ROOT)).replace("\\", "/")

def resolve_link(page: Path, raw: str, page_ids: dict[str, set[str]]) -> dict | None:
    raw = raw.strip()
    if not raw or raw.startswith(("mailto:", "tel:", "javascript:", "data:", "blob:", "//")):
        return None
    if raw.startswith(("http:", "https:")):
        return None
    parts = urlsplit(raw)
    if parts.scheme:
        return None
    if raw.startswith("#"):
        name = unquote(parts.fragment)
        return {"kind": "missing_anchor", "target": raw} if name and name not in page_ids.get(rel(page), set()) else None
    src = unquote(parts.path)
    if not src:
        return None
    if src.startswith("/"):
        # Vercel and Github Pages root paths have different deployment roots; record
        # but do not misreport these as missing repository files.
        return None
    if any(x in src for x in ("$", "{", "}", "*")):
        return None
    target = (page.parent / src).resolve()
    if not target.is_relative_to(ROOT):
        return {"kind": "outside_repo_relative_path", "target": raw}
    if target.is_dir():
        if not (target / "index.html").exists():
            return {"kind": "missing_directory_index", "target": raw}
    elif not target.is_file():
        return {"kind": "missing_static_link", "target": raw}
    else:
        frag = unquote(parts.fragment)
        # Page dynamic route anchors can be generated by JS after initial HTML parse;
        # statically referenced anchors must exist at build time.
        if frag and target.suffix == ".html":
            ids = page_ids.get(rel(target), set())
            if ids and frag not in ids:
                return {"kind": "missing_static_target_anchor", "target": raw}
    return None

def audit():
    all_html = sorted(path for p in ("platform/unified", "site", "research/voting-access")
                      for path in (ROOT / p).rglob("*.html"))
    data_files = sorted((ROOT / "data").rglob("*.json"))
    valid_json, invalid_json = 0, []
    for p in data_files:
        try:
            read_json(p)
            valid_json += 1
        except (UnicodeError, ValueError, OSError) as e:
            invalid_json.append({"path": rel(p), "message": str(e)[:180]})

    parsed = {}
    html_errors = []
    for p in all_html:
        try:
            html = p.read_text(encoding="utf-8")
            parser = PageParser()
            parser.feed(html)
            parsed[rel(p)] = (p, parser, html)
        except (UnicodeError, OSError, ValueError) as e:
            html_errors.append({"path": rel(p), "message": str(e)[:180]})
    page_ids = {p: node.ids for p, (_, node, _) in parsed.items()}
    checked_references = 0
    broken = []
    missing_bug = []
    pages = []
    data_pointers_missing = []
    resource_pat = re.compile(r"""data/[A-Za-z0-9_./-]+\.json""")
    for name, (path, page, html) in parsed.items():
        failures = []
        local_assets = 0
        for kind, raw, tag in page.links:
            if not raw.startswith(("http:", "https:", "mailto:", "tel:", "#", "//")):
                local_assets += 1
            checked_references += 1
            failure = resolve_link(path, raw, page_ids)
            if failure:
                failures.append({**failure, "page": name, "element": tag})
        if failures:
            broken.extend(failures)
        if "bug-report.js" not in page.scripts:
            missing_bug.append(name)
        pointers = set(resource_pat.findall(html))
        pointer_missing = []
        for fp in sorted(pointers):
            # Explicit dataset paths must exist. Some external API paths may be
            # stitched dynamically, so absence of a literal pointer is not a gap.
            if not (ROOT / fp).is_file():
                pointer_missing.append(fp)
                data_pointers_missing.append({"page": name, "sourcePath": fp})
        pages.append({
            "path": name, "localReferenceCount": local_assets,
            "allReferencesCount": len(page.links),
            "staticLinksBroken": len(failures),
            "bugReportScriptPresent": "bug-report.js" in page.scripts,
            "dataReferences": sorted(pointers),
            "missingDataReferences": pointer_missing,
            "primaryHeaderPresent": 'id="pa-global-header"' in html,
        })

    catalog = read_json(CATALOG)
    source_ids = {x["id"] for x in catalog["sources"]}
    gap_ids = {g["id"] for g in catalog["gaps"]}
    catalog_issues = {x for x in (g["issue"] for g in catalog["gaps"]) if x != "platform-wide"}
    source_integrity = {
        "sourceCount": len(catalog["sources"]),
        "distinctSourceIds": len(source_ids),
        "gapCount": len(catalog["gaps"]),
        "distinctGapIds": len(gap_ids),
        "nineIssuesCovered": catalog_issues == ISSUES,
        "brokenSourceReferences": [g["id"] + ":" + x for g in catalog["gaps"]
                                   for x in g["sourceIds"] if x not in source_ids],
        "missingSourceURLs": [x["id"] for x in catalog["sources"]
                              if not str(x.get("url", "")).startswith("https://")],
        "unresolvedGapCount": sum(g["status"] != "resolved_by_source_verified_data" for g in catalog["gaps"]),
    }
    graph = read_json(ROOT / "data/corporate-ownership/verified-relationships-v1.json")
    casebook = read_json(ROOT / "data/corporate-ownership/transparency-price-power-v1.json")
    inventory = read_json(ROOT / "data/research/atlas-inventory-v1.json")
    deepmap = read_json(ROOT / "data/place-impact/deep-resource-map-v1.json")
    measures = read_json(ROOT / "data/place-impact/local-measures-v1.json")
    life = read_json(ROOT / "data/place-impact/life-issues-v1.json")
    gates = read_json(ROOT / "data/health/completion-gates.json")
    queue = read_json(ROOT / "data/reconciliation/ingestion-queue.json")
    pagination = read_json(ROOT / "data/legislation/state-redistricting-pagination.json")
    stale_page_tasks = [x.get("id") for x in queue.get("tasks", [])
                        if x.get("state")=="pending" and
                        pagination.get("pages",{}).get(x.get("jurisdictionId"),{}).get(str(x.get("nextPage")),{}).get("status")=="indexed_keyword_page_not_exhaustive"]
    bounded_reconciled = sum(x.get("state")=="source_indexed_bounded_keyword_page_not_officially_adjudicated"
                             for x in queue.get("tasks", []))


    entities = {x["id"] for x in graph["entities"]}
    edge_ids = {x["id"] for x in graph["relations"]}
    broken_edges = [x["id"] for x in graph["relations"]
                    if x["from"] not in entities or x["to"] not in entities
                    or not str(x.get("source", "")).startswith("https://")]
    mapped = set(deepmap.get("inventory", {}).get("topicTags", {}))
    inventory_ids = {x["id"] for x in inventory["items"]}
    local_topic_stats = [{
        "topic": issue,
        "metricsDefined": len(measures["issues"].get(issue, {}).get("measures", [])),
        "hasReaderGuide": bool(measures["issues"].get(issue, {}).get("readerGuide")),
        "identifiedGaps": len([g for g in catalog["gaps"] if g["issue"] == issue]),
        "verifiedLocalCausalPriceEffects": 0,
        "sourceCandidates": len(set(x for g in catalog["gaps"] if g["issue"] == issue for x in g["sourceIds"])),
    } for issue in sorted(ISSUES)]

    blockers = [{
        "id": g["id"], "status": g["status"],
        "observed": g.get("observed"), "nextAction": g.get("nextAction"),
        "source": g.get("source"),
    } for g in gates.get("gates", []) if g["id"] in gates.get("blockingGates", [])]
    structural_errors = []
    if len(entities) != len(graph["entities"]) or len(edge_ids) != len(graph["relations"]):
        structural_errors.append("Duplicate corporate ownership identities or edge IDs")
    if broken_edges:
        structural_errors.append("Some corporate relations have missing endpoints or sources")
    if mapped != inventory_ids:
        structural_errors.append("Deep-research inventory and topic-map have conflicting track IDs")
    if {x["id"] for x in life["issues"]} != ISSUES or set(measures["issues"]) != ISSUES:
        structural_errors.append("One or more Daily Life categories lack a story or metric mapping")
    if len(casebook["cases"]) != casebook.get("caseCount"):
        structural_errors.append("Price-of-Power case count differs from records")
    if source_integrity["brokenSourceReferences"] or source_integrity["missingSourceURLs"]:
        structural_errors.append("Missing original-source IDs or URLs in gap catalog")
    if not source_integrity["nineIssuesCovered"]:
        structural_errors.append("Not all nine life topics have original-source gaps mapped")
    missing_routes = [p for p in IMPORTANT_ROUTES if not (ROOT / p).is_file()]
    if missing_routes:
        structural_errors.append("Core routes missing: " + ", ".join(missing_routes))
    if stale_page_tasks:
        structural_errors.append("Some source-indexed bill pages are still marked pending in ingestion queue")

    result = {
        "schema": "power-atlas.sitewide-static-source-audit.v1",
        "generatedUTC": datetime.now(timezone.utc).isoformat(),
        "overall": "research_partially_connected_not_nationwide_complete",
        "auditDefinition": "Static pages, JSON source files, internal href/src references, data pointers, issue/ownership integrity and known empirical coverage gates. NOT live API availability, browser UX, external-source URL HTTP checks, legal licensing, or completeness of a private database.",
        "repository": "jbmeadows26/Power-Atlas",
        "summary": {
            "htmlPagesAudited": len(parsed),
            "jsonDataFilesChecked": len(data_files),
            "validJsonFiles": valid_json,
            "staticReferencesInspected": checked_references,
            "unresolvedStaticLinkIssues": len(broken),
            "missingBugReportScripts": len(missing_bug),
            "unresolvedLiteralDataPointers": len(data_pointers_missing),
            "corporateEntitiesIndexed": len(entities),
            "corporateRelationsSourceAttributed": len(graph["relations"]),
            "transparencyCostCaseStudies": len(casebook["cases"]),
            "deepResearchTracksMapped": len(mapped),
            "recentResearchCollections": len(deepmap["additional"]),
            "lifeCategories": len(life["issues"]),
            "localHistoricalMeasurements": sum(x["metricsDefined"] for x in local_topic_stats),
            "unresolvedOriginalSourceGaps": source_integrity["unresolvedGapCount"],
            "originalSourceCandidates": len(source_ids),
            "blockingExistingResearchGates": len(blockers),
            "queuedIngestionTasks": sum(x.get("state")=="pending" for x in queue.get("tasks", [])),
            "stalePageTwoQueueEntries": len(stale_page_tasks),
            "boundedKeywordPageTasksReconciled": bounded_reconciled,
        },
        "sourceIntegrity": source_integrity,
        "localTopics": local_topic_stats,
        "pages": pages,
        "brokenStaticReferences": broken,
        "invalidDataFiles": invalid_json,
        "unparsedHtml": html_errors,
        "missingBugReportScripts": missing_bug,
        "unresolvedLiteralDataPointers": data_pointers_missing,
        "corporateGraph": {
            "uniqueEntities": len(entities), "sourcedLinks": len(graph["relations"]),
            "brokenRelations": broken_edges,
            "coverageCaveat": "Legal entity crosswalks, majority stakes, current portfolio, per-facility ownership and location-specific price effects remain incomplete."
        },
        "knownResearchBlockers": blockers,
        "pendingIngestionTaskIds": [x.get("id") for x in queue.get("tasks", []) if x.get("state")=="pending"],
        "staleReconciledPageTasks": stale_page_tasks,
        "keywordPaginationScope": "14 extra pages across ten jurisdictions are indexed by BillCommons. This does not establish official, multi-session, full historical state-bill completeness.",
        "unresolvedSourceCatalogPath": "data/health/sitewide-missing-sources-v1.json",
        "structuralErrors": structural_errors,
        "conclusion": "All indexed pages can be inspected for local references, but having datasets or ownership relationships does NOT prove full source ingestion or causal outcomes. Read the missing-source catalog for original links and precise required joins.",
    }
    return result

def main():
    ap=argparse.ArgumentParser()
    ap.add_argument("--output", default=str(OUT))
    ap.add_argument("--fail-on-broken-assets", action="store_true")
    args=ap.parse_args()
    result=audit()
    out=Path(args.output)
    out.parent.mkdir(parents=True,exist_ok=True)
    out.write_text(json.dumps(result,indent=2,ensure_ascii=False,allow_nan=False)+"\n",encoding="utf-8")
    print(json.dumps({"overall":result["overall"],**result["summary"],
                      "structuralErrors":result["structuralErrors"],
                      "badReferences":result["brokenStaticReferences"][:15],
                      "missingDataPointers":result["unresolvedLiteralDataPointers"][:10]},indent=2))
    if result["invalidDataFiles"] or result["structuralErrors"]:
        raise SystemExit("FATAL: invalid JSON or structural research registry")
    if args.fail_on_broken_assets and (result["brokenStaticReferences"] or result["unresolvedLiteralDataPointers"] or result["missingBugReportScripts"]):
        raise SystemExit("FATAL: broken page/static asset or missing bug-report route")

if __name__=="__main__":
    main()
